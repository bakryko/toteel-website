// State Management
let currentLang = 'ar';

// Initialize
document.addEventListener('DOMContentLoaded', () => {
    // Check saved language or detect browser lang
    const savedLang = localStorage.getItem('toteel_lang');
    if (savedLang) {
        currentLang = savedLang;
    } else {
        const userLang = navigator.language || navigator.userLanguage;
        currentLang = userLang.startsWith('en') ? 'en' : 'ar';
    }

    applyLanguage(currentLang);

    // Setup Language Toggle Button
    const langBtns = document.querySelectorAll('.lang-toggle');
    langBtns.forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            currentLang = currentLang === 'ar' ? 'en' : 'ar';
            localStorage.setItem('toteel_lang', currentLang);
            applyLanguage(currentLang);
        });
    });
});

function applyLanguage(lang) {
    // 1. Set HTML dir and lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    
    // 2. Translate all elements with data-translate attribute
    const elements = document.querySelectorAll('[data-translate]');
    elements.forEach(el => {
        const key = el.getAttribute('data-translate');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // 3. Update Wa-data targets dynamically for translation
    const waButtons = document.querySelectorAll('.req-whatsapp');
    waButtons.forEach(btn => {
        const key = btn.getAttribute('data-wa-key');
        if(key && translations[lang][key]) {
            btn.setAttribute('data-product', translations[lang][key]);
        }
    });

    // 4. Update the toggle button text itself
    const langBtns = document.querySelectorAll('.lang-toggle');
    langBtns.forEach(btn => {
        btn.textContent = translations[lang]['nav-lang'];
    });
}
